import json
import logging
from typing import Any

import httpx

from app.core.config import get_settings
from app.modules.ai.schemas import AIPlanSchema, AllowlistedStep

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "You are AutoPrep AI's dataset preparation planner. "
    "Given ONLY dataset schema and summary profile statistics (never raw rows), "
    "return a JSON object matching this exact schema: "
    "{suggested_target_column: string|null, "
    "suggested_problem_type: 'binary_classification'|'multiclass_classification'|'regression', "
    "suggested_split_strategy: 'random'|'stratified'|'time_based'|'group_based', "
    "steps: [{operation_type: one of ['drop_duplicates','cast_dtype','drop_missing_rows','drop_columns',"
    "'remove_outliers','extract_date_features','derive_ratio','drop_constant_columns','impute_missing',"
    "'scale_numeric','encode_categorical'], parameters: object, rationale: string}], "
    "explanation: string}. "
    "Never suggest arbitrary Python code."
)


def generate_deterministic_fallback_plan(
    profile_summary: dict[str, Any],
    missing_summary: dict[str, Any],
    duplicate_count: int,
    user_prompt: str,
) -> AIPlanSchema:
    """Rule-based profile-only planner when Gemini API is unavailable or unconfigured (SRS Section 11)."""
    steps: list[AllowlistedStep] = []
    columns: dict[str, Any] = profile_summary.get("columns", {})

    if duplicate_count > 0:
        steps.append(
            AllowlistedStep(
                operation_type="drop_duplicates",
                parameters={},
                rationale=f"Detected {duplicate_count} exact duplicate rows in the dataset profile.",
            )
        )

    steps.append(
        AllowlistedStep(
            operation_type="drop_constant_columns",
            parameters={},
            rationale="Remove zero-variance constant columns that add no predictive signal.",
        )
    )

    total_missing = missing_summary.get("total_missing", 0)
    if total_missing > 0:
        steps.append(
            AllowlistedStep(
                operation_type="impute_missing",
                parameters={"numeric_strategy": "median", "categorical_strategy": "most_frequent"},
                rationale=f"Detected {total_missing} missing cells; median/mode imputation will be fitted on train split only.",
            )
        )

    has_numeric = any(c.get("kind") == "numerical" for c in columns.values())
    has_categorical = any(c.get("kind") == "categorical" for c in columns.values())

    if has_numeric:
        steps.append(
            AllowlistedStep(
                operation_type="scale_numeric",
                parameters={"method": "standard"},
                rationale="Standardize numerical features (fitted on train split only) for model stability.",
            )
        )
    if has_categorical:
        steps.append(
            AllowlistedStep(
                operation_type="encode_categorical",
                parameters={"method": "onehot"},
                rationale="One-hot encode categorical columns (fitted on train split only).",
            )
        )

    last_col = list(columns.keys())[-1] if columns else None
    problem_type = "regression" if "regress" in user_prompt.lower() else "binary_classification"
    split_strategy = "random" if problem_type == "regression" else "stratified"

    return AIPlanSchema(
        suggested_target_column=last_col,
        suggested_problem_type=problem_type,
        suggested_split_strategy=split_strategy,
        steps=steps,
        explanation="Generated by deterministic fallback planner using profile metadata only (zero raw rows sent).",
    )


async def recommend_plan_with_gemini(
    profile_summary: dict[str, Any],
    missing_summary: dict[str, Any],
    duplicate_count: int,
    user_prompt: str,
) -> AIPlanSchema:
    """Call Gemini API with profile-only metadata and validate strictly against AIPlanSchema."""
    settings = get_settings()
    if settings.LLM_PROVIDER != "gemini" or not settings.GEMINI_API_KEY:
        return generate_deterministic_fallback_plan(
            profile_summary, missing_summary, duplicate_count, user_prompt
        )

    metadata_payload = {
        "user_goal": user_prompt,
        "row_count": profile_summary.get("row_count"),
        "col_count": profile_summary.get("col_count"),
        "duplicate_count": duplicate_count,
        "missing_summary": missing_summary,
        "columns": profile_summary.get("columns", {}),
    }

    url = f"https://generativelanguage.googleapis.com/v1beta/models/{settings.GEMINI_MODEL}:generateContent"
    body = {
        "system_instruction": {"parts": [{"text": SYSTEM_PROMPT}]},
        "contents": [{"role": "user", "parts": [{"text": json.dumps(metadata_payload)}]}],
        "generationConfig": {
            "temperature": 0.2,
            "responseMimeType": "application/json",
        },
    }

    try:
        async with httpx.AsyncClient(timeout=20.0) as client:
            resp = await client.post(url, params={"key": settings.GEMINI_API_KEY}, json=body)
            resp.raise_for_status()
            data = resp.json()
            raw_json = data["candidates"][0]["content"]["parts"][0]["text"]
            return AIPlanSchema.model_validate_json(raw_json)
    except Exception as exc:
        logger.warning("Gemini API call failed, falling back to deterministic planner: %s", exc)
        return generate_deterministic_fallback_plan(
            profile_summary, missing_summary, duplicate_count, user_prompt
        )
